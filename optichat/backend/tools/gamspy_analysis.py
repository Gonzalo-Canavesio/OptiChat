# Elastic relaxation
# ----------------------------------------------------------------------------


def _head_parts(head: str) -> tuple[str, str]:
    """('(i,j)', '$ (cond)') of the head of a definition, after the name."""
    head = head.strip()
    if not head.startswith("("):
        return "", head
    end = head.index(")") + 1
    return head[:end], head[end:].strip()


def _relax(container: gp.Container, equation) -> dict:
    """Elastic copy of an equation as GAMS text: lhs - sp =l= rhs, lhs + sn =g= rhs,
    both slacks for =e=. Slacks are nonnegative variables over the equation domain.

    Definitions are written as text because a deserialized equation only keeps
    the text of its algebra.
    """
    head, lhs, operator, rhs = _split_definition(equation)
    index, condition = _head_parts(head)
    slacks, body = [], lhs
    for kind, sign, applies in (("sp", "-", "=l==e="), ("sn", "+", "=g==e=")):
        if operator not in applies:
            continue
        variable = gp.Variable(
            container,
            f"{PREFIX}{kind}_{equation.name}",
            type="positive",
            domain=equation.domain,
            description=f"Elastic slack of {equation.name}",
        )
        slacks.append(variable)
        body = f"{body} {sign} {variable.name}{index}"
    relaxed = gp.Equation(
        container,
        f"{PREFIX}rx_{equation.name}",
        domain=equation.domain,
        description=equation.description,
    )
    left = f"{relaxed.name}{index}{f' {condition}' if condition else ''}"
    right = f"{body} {operator} {rhs}"
    relaxed._definition = Expression(left, "..", right)
    total = " + ".join(
        f"sum({index} {condition}, {v.name}{index})" if index else v.name
        for v in slacks
    )
    code = [
        f"{v.name}.{attribute}{index} = {value};"
        for v in slacks
        for attribute, value in (("lo", 0), ("up", "inf"), ("l", 0))
    ]
    return {
        "equation": relaxed,
        "slacks": slacks,
        "index": index,
        "total": total,
        "code": [*code, f"{left} .. {right};"],
    }


def _violated_rows(relaxation) -> dict[tuple, float]:
    """{row labels: total slack} of the rows that phase 1 had to relax."""
    totals: dict[tuple, float] = {}
    for variable in relaxation["slacks"]:
        if variable.dimension == 0:
            totals[()] = totals.get((), 0.0) + _level(variable)
            continue
        for labels, (level, *_) in _records(variable):
            key = tuple(map(str, labels))
            totals[key] = totals.get(key, 0.0) + float(level)
    return {labels: total for labels, total in totals.items() if total > VIOLATION_TOL}


def _quote(label: str) -> str:
    return f'"{label}"' if "'" in label else f"'{label}'"


def _fix_slacks(relaxation, rows: list[tuple]) -> list[str]:
    """GAMS code that lets only the given rows relax: other slacks are fixed to 0."""
    index = relaxation["index"]
    if not index:
        return []
    code = []
    for variable in relaxation["slacks"]:
        code += [f"{variable.name}.up{index} = 0;", f"{variable.name}.l{index} = 0;"]
        code += [
            f"{variable.name}.up({','.join(map(_quote, labels))}) = inf;"
            for labels in rows
        ]
    return code


def _total_variable(container, name: str, total: str) -> tuple:
    """(variable, equation, GAMS code) defining a free variable as `total`."""
    variable = gp.Variable(container, name)
    equation = gp.Equation(container, f"{name}_def")
    right = f"{total} =e= {name}"
    equation._definition = Expression(equation.name, "..", right)
    return variable, equation, f"{equation.name} .. {right};"


def elastic_relaxation(
    model: gp.Model, penalty: float = 10.0
) -> tuple[gp.Model, dict[str, float]]:
    """Locate the rows that make a model infeasible and build a relaxed model.

    Phase 1 minimises the total elastic slack of every non-objective equation with
    the active solver; rows with slack > 1e-6 are the violations ({row: amount}).
    The returned model, named '<name>_relaxed' and not solved, keeps the original
    equations but replaces those with violated rows by elastic copies in which
    only the violated rows may relax, penalised in the objective (+ for MIN,
    - for MAX). Its objective variable is defined by the original objective
    equation, kept as a row. RuntimeError if phase 1 is not solved.
    """
    container = model.container
    autogen = set(model._autogen_symbols)
    definition = _objective_equation(model)
    skipped = autogen | ({definition[0].name} if definition is not None else set())
    relaxations = {
        eq.name: _relax(container, eq)
        for eq in model.equations
        if eq.name not in skipped
    }
    if not relaxations:
        raise RuntimeError("The model has no constraint to relax.")

    total, total_eq, total_code = _total_variable(
        container,
        f"{PREFIX}{model.name}_phase1_total",
        " + ".join(r["total"] for r in relaxations.values()),
    )
    container.addGamsCode(
        "\n".join([*(c for r in relaxations.values() for c in r["code"]), total_code])
    )
    phase1 = gp.Model(
        container,
        name=f"{PREFIX}{model.name}_phase1",
        equations=[*(r["equation"] for r in relaxations.values()), total_eq],
        problem=model.problem,
        sense=gp.Sense.MIN,
        objective=total,
    )
    phase1.solve(solver=get_solver_gamspy_name())
    if phase1.status not in _OPTIMAL | _FEASIBLE:
        raise RuntimeError(
            f"The elastic relaxation could not be solved ({phase1.status.name})."
        )

    violations, violated = {}, {}
    for eq in model.equations:
        rows = _violated_rows(relaxations[eq.name]) if eq.name in relaxations else {}
        if rows:
            violated[eq.name] = list(rows)
            violations.update(
                {_name(eq, list(labels)): value for labels, value in rows.items()}
            )

    penalty_var, penalty_eq, penalty_code = _total_variable(
        container,
        f"{PREFIX}{model.name}_penalty",
        " + ".join(relaxations[name]["total"] for name in violated) or "0",
    )
    container.addGamsCode(
        "\n".join(
            [
                *(
                    c
                    for name, rows in violated.items()
                    for c in _fix_slacks(relaxations[name], rows)
                ),
                penalty_code,
            ]
        )
    )
    equations = [
        relaxations[eq.name]["equation"] if eq.name in violated else eq
        for eq in model.equations
    ]
    objective = _objective_variable(model)
    if objective is None:
        sense, objective = gp.Sense.MIN, penalty * penalty_var
    elif model.sense == gp.Sense.MAX:
        sense, objective = model.sense, objective - penalty * penalty_var
    else:
        sense, objective = model.sense, objective + penalty * penalty_var
    relaxed = gp.Model(
        container,
        name=f"{model.name}_relaxed",
        equations=[*equations, penalty_eq],
        problem=model.problem,
        sense=sense,
        objective=objective,
    )
    return relaxed, violations
