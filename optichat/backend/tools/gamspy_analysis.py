"""Robustness analysis and infeasibility diagnosis primitives for GAMSPy models.

Rows are evaluated by GAMS itself: each equation definition is rewritten as a
parameter assignment over the same domain, with every variable read at its level,
so the bodies follow the current parameter values without re-solving.
"""

import re
from collections.abc import Mapping, Sequence
from pathlib import Path

import gamspy as gp
import numpy as np
import pandas as pd
from gamspy._algebra.expression import Expression

from optichat.backend.config.solver import get_solver_gamspy_name
from optichat.backend.tools.gamspy_extractor import (
    _FEASIBLE,
    _OPTIMAL,
    _SENSES,
    HELPER_PREFIX,
    _name,
    _records,
)
from optichat.backend.tools.robust_analysis.robustness_analysis import _save_df
from optichat.backend.tools.robust_analysis.scenario_generator import (
    _sample_normal_clipped,
    _sample_uniform,
)

PREFIX = HELPER_PREFIX
VIOLATION_TOL = 1e-6

_OPERATOR = re.compile(r"=[elg]=")
_TOKEN = re.compile(r"'[^']*'|\"[^\"]*\"|[A-Za-z_]\w*")
_ENTRY = re.compile(r"^\s*([A-Za-z_]\w*)\s*(?:\[(.*)\])?\s*$")


# ----------------------------------------------------------------------------
# Row evaluation
# ----------------------------------------------------------------------------


def _split_definition(equation) -> tuple[str, str, str, str]:
    """(head after the equation name, lhs, GAMS operator, rhs) of a definition."""
    head, body = equation.getDefinition().split(" .. ", 1)
    body = body.strip().rstrip(";")
    operator = _OPERATOR.search(body)
    if operator is None:
        raise ValueError(f"Unsupported definition for equation '{equation.name}'.")
    return (
        head.strip()[len(equation.name) :],
        body[: operator.start()].strip(),
        operator.group(0),
        body[operator.end() :].strip(),
    )


def _at_levels(text: str, var_names: set[str]) -> str:
    """GAMS text with every variable replaced by its level (x(i) -> x.l(i))."""

    def level(match):
        token = match.group(0)
        start, end = match.span()
        if (
            token[0] in "'\""
            or token.casefold() not in var_names
            or text[start - 1 : start] == "."
            or text[end : end + 1] == "."
        ):
            return token
        return f"{token}.l"

    return _TOKEN.sub(level, text)


def _helper_parameter(container: gp.Container, name: str, domain) -> gp.Parameter:
    if name in container:
        return container[name]
    return gp.Parameter(container, name, domain=domain)


def _evaluate(model: gp.Model, equations) -> dict[str, dict[tuple, float]]:
    """{equation name: {row labels: lhs - rhs}} at the current levels and values."""
    container = model.container
    var_names = {v.name.casefold() for v in container.getVariables()}
    code, helpers = [], []
    for equation in equations:
        head, lhs, _, rhs = _split_definition(equation)
        value = _helper_parameter(
            container, f"{PREFIX}ev_{equation.name}", equation.domain
        )
        rows = _helper_parameter(
            container, f"{PREFIX}rows_{equation.name}", equation.domain
        )
        code += [
            f"option clear = {value.name};",
            f"option clear = {rows.name};",
            f"{value.name}{head} = ({_at_levels(lhs, var_names)})"
            f" - ({_at_levels(rhs, var_names)});",
            f"{rows.name}{head} = 1;",
        ]
        helpers.append((equation, value, rows))
    if code:
        container.addGamsCode("\n".join(code))

    bodies = {}
    for equation, value, rows in helpers:
        if equation.dimension == 0:
            bodies[equation.name] = {(): float(value.toValue() or 0.0)}
            continue
        # GAMS drops zero values: a row missing from `value` has body 0
        values = {
            tuple(map(str, labels)): float(v) for labels, (v, *_) in _records(value)
        }
        bodies[equation.name] = {
            key: values.get(key, 0.0)
            for key in (tuple(map(str, labels)) for labels, _ in _records(rows))
        }
    return bodies


def _row_equations(model: gp.Model) -> list:
    autogen = set(model._autogen_symbols)
    return [eq for eq in model.equations if eq.name not in autogen]


def evaluate_rows(model: gp.Model) -> dict[str, float]:
    """Body (lhs - rhs) of every row, named like the extractor ('eq[a,b]').

    The autogenerated objective equation is left out.
    """
    return _rows(model, _evaluate(model, _row_equations(model)))


def _rows(model: gp.Model, bodies: dict) -> dict[str, float]:
    return {
        _name(eq, labels): body
        for eq in _row_equations(model)
        for labels, body in bodies[eq.name].items()
    }


def row_senses(model: gp.Model) -> dict[str, str]:
    """Sense ('<=', '>=', '==') of every row returned by evaluate_rows."""
    senses = {}
    rows = _evaluate(model, _row_equations(model))
    for equation in _row_equations(model):
        sense = _SENSES[_split_definition(equation)[2]]
        for labels in rows[equation.name]:
            senses[_name(equation, labels)] = sense
    return senses


def _objective_variable(model: gp.Model):
    objective = model._objective
    if isinstance(objective, gp.Variable):
        return objective
    # A model built on another one's objective also lists that one's symbols
    own = f"{model.name}_objective_variable"
    for name in sorted(model._autogen_symbols, key=lambda n: n != own):
        symbol = model.container[name]
        if isinstance(symbol, gp.Variable):
            return symbol
    return None


def _bare(text: str) -> str:
    text = text.strip()
    while text.startswith("(") and text.endswith(")"):
        text = text[1:-1].strip()
    return text.casefold()


def _objective_equation(model: gp.Model):
    """(equation defining the objective variable z, sign) so that the objective
    is z.l + sign * body, or None when there is no such equation."""
    variable = _objective_variable(model)
    if variable is None:
        return None
    autogen = set(model._autogen_symbols)
    name = variable.name.casefold()
    equations = sorted(model.equations, key=lambda eq: eq.name not in autogen)
    for equation in equations:
        if equation.dimension:
            continue
        _, lhs, operator, rhs = _split_definition(equation)
        if operator != "=e=":
            continue
        if _bare(rhs) == name:
            return equation, 1.0
        if _bare(lhs) == name:
            return equation, -1.0
    return None


def _level(variable) -> float:
    records = variable.records
    if records is None or records.empty:
        return 0.0
    return float(records["level"].iloc[0])


def evaluate_objective(model: gp.Model) -> float | None:
    """Objective at the current levels and parameter values, without solving.

    None when the objective is not a variable defined by an '=e=' equation.
    """
    definition = _objective_equation(model)
    if definition is None:
        return None
    equation, sign = definition
    body = _evaluate(model, [equation])[equation.name][()]
    return _level(_objective_variable(model)) + sign * body


