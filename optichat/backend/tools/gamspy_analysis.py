def _parameter(model: gp.Model, name: str) -> gp.Parameter:
    container = model.container
    if name not in container:
        raise ValueError(f"Parameter '{name}' is unknown in this model.")
    symbol = container[name]
    if not isinstance(symbol, gp.Parameter):
        raise ValueError(f"'{name}' is not a parameter of this model.")
    return symbol


def _parse_entry(model: gp.Model, entry_name: str) -> tuple[gp.Parameter, list | None]:
    """(parameter, labels) of 'p[a,b]'; labels is None for a bare name."""
    match = _ENTRY.match(entry_name)
    if match is None:
        raise ValueError(f"Parameter '{entry_name}' is unknown in this model.")
    parameter = _parameter(model, match.group(1))
    if match.group(2) is None:
        return parameter, None
    labels = [label.strip().strip("'\"") for label in match.group(2).split(",")]
    if len(labels) != parameter.dimension:
        raise ValueError(
            f"Parameter '{parameter.name}' has {parameter.dimension} indices, "
            f"got '{entry_name}'."
        )
    return parameter, labels


def _canonical_labels(parameter: gp.Parameter, labels: list) -> list[str]:
    """Labels as stored in the records (GAMS labels are case-insensitive)."""
    wanted = [label.casefold() for label in labels]
    for record_labels, _ in _records(parameter):
        if [str(label).casefold() for label in record_labels] == wanted:
            return list(map(str, record_labels))
    canonical = []
    for label, domain in zip(labels, parameter.domain):
        members = (
            [str(row[0]) for row in domain.records.itertuples(index=False)]
            if not isinstance(domain, str) and domain.records is not None
            else None
        )
        if members is None:
            canonical.append(label)
            continue
        match = [member for member in members if member.casefold() == label.casefold()]
        if not match:
            raise ValueError(
                f"Index '{','.join(labels)}' is not in the domain of parameter "
                f"'{parameter.name}'."
            )
        canonical.append(match[0])
    return canonical


def expand_param_entries(model: gp.Model, name: str) -> list[tuple[str, list[str]]]:
    """[(entry name, labels)] of a parameter name.

    'p[a,b]' is one entry, a bare indexed name expands into one entry per record
    (indices whose value is 0 have no record) and a scalar is itself.
    """
    parameter, labels = _parse_entry(model, name)
    if labels is not None:
        labels = _canonical_labels(parameter, labels)
        return [(_name(parameter, labels), labels)]
    if parameter.dimension == 0:
        return [(parameter.name, [])]
    return [
        (_name(parameter, list(map(str, record_labels))), list(map(str, record_labels)))
        for record_labels, _ in _records(parameter)
    ]


def _values(parameter: gp.Parameter) -> dict[tuple, float]:
    if parameter.dimension == 0:
        return {(): float(parameter.toValue() or 0.0)}
    return {
        tuple(map(str, labels)): float(value)
        for labels, (value, *_) in _records(parameter)
    }


def _set_values(parameter: gp.Parameter, values: dict[tuple, float]) -> None:
    if parameter.dimension == 0:
        parameter.setRecords(values[()])
    else:
        parameter.setRecords([(*labels, value) for labels, value in values.items()])


def current_value(model: gp.Model, entry_name: str) -> float:
    """Current value of a scalar parameter or a parameter entry ('p[a,b]')."""
    entries = expand_param_entries(model, entry_name)
    parameter, _ = _parse_entry(model, entry_name)
    if len(entries) != 1 or (parameter.dimension and "[" not in entry_name):
        raise ValueError(f"'{entry_name}' is an indexed parameter, name one entry.")
    return _values(parameter).get(tuple(entries[0][1]), 0.0)


def _expand(model: gp.Model, names: list[str]) -> list[tuple[str, gp.Parameter, tuple]]:
    expanded = []
    for name in names:
        parameter, _ = _parse_entry(model, name)
        for entry_name, labels in expand_param_entries(model, name):
            expanded.append((entry_name, parameter, tuple(labels)))
    return expanded


# ----------------------------------------------------------------------------
# Slack-based robustness
# ----------------------------------------------------------------------------


def _sides(sense: str, body: float) -> list[tuple[float, str]]:
    """(slack, bound type) of each side of a row; slack >= 0 when satisfied."""
    sides = []
    if sense in ("<=", "=="):
        sides.append((-body, "upper"))
    if sense in (">=", "=="):
        sides.append((body, "lower"))
    return sides


def _room_pct(change: float, value: float) -> float:
    return change / abs(value) * 100.0 if abs(value) > 1e-10 else float("inf")


def _entry_slack(value, before, after, senses, h, tol) -> dict:
    binding, non_binding = [], []
    for row, body in before.items():
        for (slack, bound_type), (slack_after, _) in zip(
            _sides(senses[row], body), _sides(senses[row], after[row])
        ):
            sensitivity = (slack_after - slack) / h
            if abs(sensitivity) < 1e-10:
                continue
            if slack <= tol:
                binding.append(
                    {"constraint": row, "slack": 0.0, "bound_type": bound_type}
                )
                continue
            change = slack / abs(sensitivity)
            non_binding.append(
                {
                    "constraint": row,
                    "slack": round(slack, 6),
                    "slack_sensitivity": round(sensitivity, 6),
                    "direction": "increase" if sensitivity < 0 else "decrease",
                    "max_allowable_change": round(change, 6),
                    "room_pct": round(_room_pct(change, value), 2),
                    "bound_type": bound_type,
                }
            )
    tightest = (
        min(non_binding, key=lambda c: c["max_allowable_change"])
        if non_binding
        else None
    )
    return {
        "current_value": value,
        "binding_constraints": binding,
        "non_binding_constraints": non_binding,
        "has_any_binding": len(binding) > 0,
        "overall_max_change": tightest["max_allowable_change"] if tightest else None,
        "overall_room_pct": tightest["room_pct"] if tightest else None,
        "overall_direction": tightest["direction"] if tightest else None,
        "tightest_constraint": tightest["constraint"] if tightest else None,
    }


def slack_analysis(
    model: gp.Model, uncertain_param_names: list[str], tol: float = 1e-6
) -> dict:
    """How far each parameter entry can move before a row reaches its bound, at the
    current levels (no re-solve), in the format of _compute_slack_analysis.

    Each entry is perturbed once by h = max(|v| * 1e-5, 1e-7) and every row body is
    re-evaluated: a positive slack sensitivity means decreasing the parameter
    tightens the row. Unknown names raise ValueError.
    """
    expanded = _expand(model, uncertain_param_names)
    senses = row_senses(model)
    before = evaluate_rows(model)
    results = {}
    for entry_name, parameter, labels in expanded:
        original = _values(parameter)
        value = original.get(labels, 0.0)
        h = max(abs(value) * 1e-5, 1e-7)
        try:
            _set_values(parameter, {**original, labels: value + h})
            after = evaluate_rows(model)
        except Exception as error:
            results[entry_name] = {"error": f"Cannot evaluate the rows: {error}"}
            continue
        finally:
            _set_values(parameter, original)
        results[entry_name] = _entry_slack(value, before, after, senses, h, tol)
    return results


# ----------------------------------------------------------------------------
# Scenario-based robustness
# ----------------------------------------------------------------------------


def _is_pair(bound) -> bool:
    return (
        isinstance(bound, Sequence)
        and not isinstance(bound, str)
        and len(bound) == 2
        and all(isinstance(b, (int, float, np.number)) for b in bound)
    )


def _label_key(key) -> tuple:
    if isinstance(key, str):
        return tuple(label.strip() for label in key.split(","))
    if isinstance(key, Sequence):
        return tuple(map(str, key))
    return (str(key),)


def _entry_bounds(model: gp.Model, name: str, bound) -> list[tuple]:
    """[(entry name, parameter, labels, (lb, ub))] for one name and its bounds."""
    parameter, _ = _parse_entry(model, name)
    entries = expand_param_entries(model, name)
    if _is_pair(bound):
        pairs = [bound] * len(entries)
    elif isinstance(bound, Mapping):
        by_labels = {_label_key(k).__repr__().casefold(): v for k, v in bound.items()}
        try:
            pairs = [
                by_labels[tuple(labels).__repr__().casefold()] for _, labels in entries
            ]
        except KeyError as missing:
            raise ValueError(
                f"Bounds for '{name}' miss an index: {missing}."
            ) from missing
    elif (
        isinstance(bound, Sequence)
        and len(bound) == len(entries)
        and all(_is_pair(b) for b in bound)
    ):
        pairs = list(bound)
    else:
        raise ValueError(
            f"Bounds for '{name}' must be (lb, ub), a dict {{index: (lb, ub)}} or "
            "a sequence of (lb, ub) aligned to its entries."
        )
    out = []
    for (entry_name, labels), (lb, ub) in zip(entries, pairs):
        if float(lb) > float(ub):
            raise ValueError(f"Bounds for '{entry_name}' have lb > ub.")
        out.append((entry_name, parameter, tuple(labels), (float(lb), float(ub))))
    return out


def _sample(bounds, n_scenarios, dist, seed) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    columns = {}
    for entry_name, _, _, (lb, ub) in bounds:
        if dist == "uniform" or ub == lb:
            columns[entry_name] = _sample_uniform(lb, ub, n_scenarios, rng)
        else:
            columns[entry_name] = _sample_normal_clipped(
                lb, ub, 0.5 * (lb + ub), (ub - lb) / 6.0, n_scenarios, rng
            )
    scenarios = pd.DataFrame(columns)
    scenarios.insert(0, "scenario_id", np.arange(1, n_scenarios + 1, dtype=int))
    return scenarios


def _violated(sense: str, body: float, tol: float) -> bool:
    return any(slack < -tol for slack, _ in _sides(sense, body))


def run_scenario_robustness(
    model: gp.Model,
    uncertain_param_names: list[str],
    bounds: list,
    n_scenarios: int,
    dist: str = "uniform",
    seed: int | None = None,
    out_path: str = "robust_results.csv",
    tol: float = 1e-6,
) -> pd.DataFrame:
    """Evaluate the current solution on sampled parameter scenarios, like
    run_robustness: no re-solve, original parameter values restored afterwards.

    `bounds` aligns with the names: (lb, ub) per entry; a bare indexed name also
    takes a dict {labels: (lb, ub)} or a sequence of (lb, ub) per record. Columns:
    scenario_id, one per parameter entry, objective, then one 0/1 violation flag
    per row. Results go to `out_path`, scenarios to `out_path + ".scenarios.csv"`.
    """
    if n_scenarios <= 0:
        raise ValueError("n_scenarios must be positive.")
    dist = (dist or "uniform").strip().lower()
    if dist not in ("uniform", "normal"):
        raise ValueError("dist must be 'uniform' or 'normal'.")
    if len(uncertain_param_names) != len(bounds):
        raise ValueError(
            "`uncertain_param_names` and `bounds` must have the same length."
        )

    entry_bounds = [
        entry
        for name, bound in zip(uncertain_param_names, bounds)
        for entry in _entry_bounds(model, name, bound)
    ]
    scenarios = _sample(entry_bounds, n_scenarios, dist, seed)
    scenarios_out = Path(out_path).with_suffix(Path(out_path).suffix + ".scenarios.csv")
    scenarios_out.parent.mkdir(parents=True, exist_ok=True)
    scenarios.to_csv(scenarios_out, index=False)

    parameters = {parameter.name: parameter for _, parameter, _, _ in entry_bounds}
    originals = {name: _values(parameter) for name, parameter in parameters.items()}
    senses = row_senses(model)
    objective = _objective_equation(model)
    equations = _row_equations(model)
    if objective is not None and objective[0] not in equations:
        equations.append(objective[0])

    rows = []
    try:
        for _, scenario in scenarios.iterrows():
            values = {name: dict(original) for name, original in originals.items()}
            for entry_name, parameter, labels, _ in entry_bounds:
                values[parameter.name][labels] = float(scenario[entry_name])
            for name, parameter in parameters.items():
                _set_values(parameter, values[name])
            bodies = _evaluate(model, equations)
            row = {"scenario_id": int(scenario["scenario_id"])}
            row.update(
                {
                    entry_name: float(scenario[entry_name])
                    for entry_name, *_ in entry_bounds
                }
            )
            row["objective"] = (
                None
                if objective is None
                else _level(_objective_variable(model))
                + objective[1] * bodies[objective[0].name][()]
            )
            row.update(
                {
                    name: int(_violated(senses[name], body, tol))
                    for name, body in _rows(model, bodies).items()
                }
            )
            rows.append(row)
    finally:
        for name, parameter in parameters.items():
            _set_values(parameter, originals[name])

    results = pd.DataFrame(rows)
    _save_df(results, out_path)
    return results


